/* Bundle the isolated content script and preview sandbox from their modules.
 * No remote code or runtime function serialization crosses either boundary. */
import { stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';
import { previewSandboxBundle } from './build/preview-sandbox.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'dist/packages/bridge/src/page-entry.js');
const output = path.join(root, 'apps/extension/public/mitter-page.js');

await build({
  input: entry,
  platform: 'browser',
  output: {
    file: output,
    format: 'iife',
    banner: '/* Generated by scripts/build-page.mjs. Source: packages/bridge/src. */',
  },
});

const bundledFile = await stat(output);
console.log(`Packaged persistent page bridge (${bundledFile.size} bytes).`);

const sandboxSource = await previewSandboxBundle(root);
const sandboxOutput = path.join(root, 'apps/extension/public/preview-sandbox.js');
await writeFile(sandboxOutput, sandboxSource, 'utf8');
const sandboxFile = await stat(sandboxOutput);
console.log(`Packaged isolated preview sandbox (${sandboxFile.size} bytes).`);
